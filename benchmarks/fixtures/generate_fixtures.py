#!/usr/bin/env python3
"""
Test fixture generator for Taurus XML benchmark suite.
Generates XML files with various patterns for comprehensive testing.
"""

import os
import sys
import random
from pathlib import Path

def generate_deep_nesting(max_depth, elements_per_level=1):
    """Generate deeply nested XML structure."""
    xml = '<?xml version="1.0"?>\n'
    indent = 0

    for i in range(max_depth):
        xml += '  ' * indent + f'<level{i}>\n'
        indent += 1

    # Add content at deepest level
    xml += '  ' * indent + '<content>Deep content</content>\n'

    for i in range(max_depth - 1, -1, -1):
        indent -= 1
        xml += '  ' * indent + f'</level{i}>\n'

    return xml

def generate_wide_siblings(sibling_count, attrs_per_element=0):
    """Generate XML with many siblings at same level."""
    xml = '<?xml version="1.0"?>\n'
    xml += '<root>\n'

    for i in range(sibling_count):
        attrs = ''
        if attrs_per_element > 0:
            attrs = ' ' + ' '.join([f'attr{j}="value{j}"' for j in range(attrs_per_element)])
        xml += f'  <item id="{i}"{attrs}>Content {i}</item>\n'

    xml += '</root>\n'
    return xml

def generate_heavy_attributes(element_count, attrs_per_element):
    """Generate XML with many attributes per element."""
    xml = '<?xml version="1.0"?>\n'
    xml += '<root>\n'

    for i in range(element_count):
        attrs = ' '.join([f'attr{j}="value{j}_{i}"' for j in range(attrs_per_element)])
        xml += f'  <element id="{i}" {attrs}>Content {i}</element>\n'

    xml += '</root>\n'
    return xml

def generate_namespaces(element_count, ns_count):
    """Generate XML with heavy namespace usage."""
    xml = '<?xml version="1.0"?>\n'

    # Declare namespaces
    ns_decls = ' '.join([f'xmlns:ns{j}="http://example.com/ns{j}"' for j in range(ns_count)])
    xml += f'<root {ns_decls}>\n'

    for i in range(element_count):
        ns_idx = i % ns_count
        xml += f'  <ns{ns_idx}:element ns{ns_idx}:attr="value">Content {i}</ns{ns_idx}:element>\n'

    xml += '</root>\n'
    return xml

def generate_mixed_content(element_count):
    """Generate XML with mixed content (text, elements, comments, CDATA)."""
    xml = '<?xml version="1.0"?>\n'
    xml += '<root>\n'

    for i in range(element_count):
        content_type = i % 5

        if content_type == 0:
            xml += f'  <item>Text content {i}</item>\n'
        elif content_type == 1:
            xml += f'  <item>\n    <child>Nested {i}</child>\n  </item>\n'
        elif content_type == 2:
            xml += f'  <!-- Comment {i} -->\n  <item>After comment</item>\n'
        elif content_type == 3:
            xml += f'  <item><![CDATA[CDATA content {i} with <special> & characters]]></item>\n'
        else:
            xml += f'  Mixed text <b>bold</b> and <i>italic</i> content {i}\n'

    xml += '</root>\n'
    return xml

def generate_realistic_document(element_count):
    """Generate a realistic XML document structure."""
    xml = '''<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE document SYSTEM "document.dtd">
<!--
  Sample document for benchmarking
  Generated by fixture_generator.py
-->
<document version="1.0" lang="en">
  <header>
    <title>Benchmark Document</title>
    <author>Test Generator</author>
    <date>2026-03-01</date>
    <metadata>
      <meta name="generator" value="fixture_generator"/>
      <meta name="purpose" value="benchmarking"/>
    </metadata>
  </header>
  <body>
'''

    for i in range(element_count):
        section_type = i % 4

        if section_type == 0:
            xml += f'''    <section id="sec{i}">
      <title>Section {i}</title>
      <paragraph>This is paragraph {i} with some text content.</paragraph>
      <paragraph>Another paragraph with <emphasis>emphasized</emphasis> text.</paragraph>
    </section>
'''
        elif section_type == 1:
            xml += f'''    <list id="list{i}" type="ordered">
      <item>Item 1 of list {i}</item>
      <item>Item 2 of list {i}</item>
      <item>Item 3 of list {i}</item>
    </list>
'''
        elif section_type == 2:
            xml += f'''    <table id="table{i}">
      <row><cell>A{i}</cell><cell>B{i}</cell></row>
      <row><cell>C{i}</cell><cell>D{i}</cell></row>
    </table>
'''
        else:
            xml += f'''    <note priority="medium" id="note{i}">
      <text>Note content {i}</text>
    </note>
'''

    xml += '''  </body>
  <footer>
    <copyright>2026 Test Generator</copyright>
  </footer>
</document>
'''
    return xml

def main():
    fixtures_dir = Path(__file__).parent / 'data'
    fixtures_dir.mkdir(exist_ok=True)

    fixtures = [
        # Tiny
        ('tiny.xml', generate_realistic_document(5)),

        # Small
        ('small.xml', generate_realistic_document(50)),

        # Medium
        ('medium.xml', generate_realistic_document(500)),

        # Large
        ('large.xml', generate_realistic_document(5000)),

        # Extra large
        ('xlarge.xml', generate_realistic_document(20000)),

        # Deep nesting
        ('deep_50.xml', generate_deep_nesting(50)),
        ('deep_100.xml', generate_deep_nesting(100)),
        ('deep_500.xml', generate_deep_nesting(500)),
        ('deep_1000.xml', generate_deep_nesting(1000)),

        # Wide siblings
        ('wide_100.xml', generate_wide_siblings(100)),
        ('wide_500.xml', generate_wide_siblings(500)),
        ('wide_1000.xml', generate_wide_siblings(1000)),
        ('wide_5000.xml', generate_wide_siblings(5000)),
        ('wide_10000.xml', generate_wide_siblings(10000)),

        # Heavy attributes
        ('attrs_5.xml', generate_heavy_attributes(1000, 5)),
        ('attrs_10.xml', generate_heavy_attributes(1000, 10)),
        ('attrs_20.xml', generate_heavy_attributes(1000, 20)),
        ('attrs_50.xml', generate_heavy_attributes(500, 50)),
        ('attrs_100.xml', generate_heavy_attributes(500, 100)),

        # Namespaces
        ('ns_5.xml', generate_namespaces(1000, 5)),
        ('ns_10.xml', generate_namespaces(1000, 10)),
        ('ns_20.xml', generate_namespaces(1000, 20)),

        # Mixed content
        ('mixed_100.xml', generate_mixed_content(100)),
        ('mixed_500.xml', generate_mixed_content(500)),
        ('mixed_1000.xml', generate_mixed_content(1000)),
    ]

    print(f"Generating {len(fixtures)} test fixtures in {fixtures_dir}/")
    print("-" * 60)

    for filename, content in fixtures:
        filepath = fixtures_dir / filename
        filepath.write_text(content)
        size = len(content)
        print(f"  {filename:20s} {size:>10,} bytes ({size/1024:.1f} KB)")

    print("-" * 60)
    print(f"Done! {len(fixtures)} fixtures generated.")

if __name__ == '__main__':
    main()
